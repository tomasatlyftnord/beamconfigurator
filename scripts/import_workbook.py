#!/usr/bin/env python3
"""Read the reviewed source without modifying it; export offline data and Excel fixtures.

Usage: python scripts/import_workbook.py path/to/source.xlsx
Requires openpyxl only when importing a new source, never to run the application.
"""
import csv
import hashlib
import json
from pathlib import Path
import sys
import unicodedata

import openpyxl
from openpyxl.worksheet.formula import ArrayFormula

ROOT = Path(__file__).resolve().parents[1]


def normal(value):
    return unicodedata.normalize("NFKC", value) if isinstance(value, str) else value


def extract(path):
    formulas = openpyxl.load_workbook(path, data_only=False)
    cached = openpyxl.load_workbook(path, data_only=True)
    source = {"fileName": path.name, "version": "0.1 – granskning",
              "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}
    profiles = []
    sheet = cached["Balkprofiler"]
    suspect_rows = {
        82: "Wₓ och Iₓ är inbördes oförenliga för angiven höjd; rätt värde kan inte fastställas ur arbetsboken.",
        152: "Wₓ och Iₓ är inbördes oförenliga för angiven höjd; rätt värde kan inte fastställas ur arbetsboken.",
        173: "Area och massa per meter är inbördes oförenliga för stål i arbetsboken.",
        174: "Area och massa per meter är inbördes oförenliga för stål i arbetsboken.",
        204: "Area saknas, Iᵧ/Kv är noll och Wₓ stämmer inte med Iₓ och angiven höjd. Profildata behöver verifieras."
    }
    for row in range(28, 232):
        cols = {openpyxl.utils.get_column_letter(col): sheet.cell(row, col).value for col in range(2, 17)}
        name = cols["B"]
        family = "HEA" if name.startswith("HE ") else ("SHS" if name.split("x")[0] == name.split("x")[1] else "RHS")
        warnings = []
        if row in suspect_rows:
            warnings.append(f"Balkprofiler!B{row}: {suspect_rows[row]}")
        if 112 <= row <= 122:
            warnings.append(f"Balkprofiler!J{row}/N{row}: tabellens tröghetsradier avviker från √(I/A). Beräkningsfallen använder √(I/A).")
        if family == "HEA":
            warnings.append(f"Balkprofiler!G{row}: HEA-arean har enhetskonflikt (rubrik mm², tal i cm²); tryck/knäckning kan inte verifieras med råvärdet. Iᵧ och Kv saknas också.")
        if row == 218:
            warnings.append("Balkprofiler!G218: HE 180 A har dessutom arean 15,3, som är oförenlig med vikt och tröghetsradie.")
        def scaled(col, factor):
            val = cols[col]
            return val * factor if isinstance(val, (float, int)) else None
        profiles.append({"index": row - 27, "row": row, "name": name, "family": family,
                         "W": scaled("C", 1000), "Ix": scaled("H", 10000), "Iy": scaled("K", 10000),
                         "A": cols["G"], "Kv": scaled("O", 10000), "mass": cols["E"],
                         "wxCm3": cols["C"], "ixCm4": cols["H"], "iyCm4": cols["K"],
                         "kvCm4": cols["O"], "columns": cols, "validityWarnings": warnings})
    buckling = [{"row": row, "lambda": cached["KNÄCKTABELL"].cell(row, 1).value,
                 "stress": cached["KNÄCKTABELL"].cell(row, 2).value} for row in range(7, 30)]
    sheets = []
    for sheet in formulas:
        if sheet.title in ("Balkprofiler", "KNÄCKTABELL"):
            continue
        cells = {}
        for row in sheet:
            for cell in row:
                if cell.value is None:
                    continue
                formula = cell.value.text if isinstance(cell.value, ArrayFormula) else (cell.value if cell.data_type == "f" else None)
                cells[cell.coordinate] = {
                    "value": None if formula else cell.value,
                    "formula": formula, "cached": cached[sheet.title][cell.coordinate].value,
                    "label": normal(sheet.cell(cell.row, 2).value),
                    "unit": normal(sheet.cell(cell.row, 6).value),
                }
        sheets.append({"name": sheet.title, "cells": cells})
    return {"source": source, "profiles": profiles, "buckling": buckling, "sheets": sheets}


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    data = extract(Path(sys.argv[1]))
    payload = json.dumps(data, ensure_ascii=False, indent=2, allow_nan=False)
    (ROOT / "workbook-data.js").write_text(
        "// Generated by scripts/import_workbook.py. Raw source values; see data/WORKBOOK.md.\n"
        "(function (root) {\n  'use strict';\n  const data = " + payload + ";\n"
        "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
        "  root.WorkbookData = data;\n})(typeof globalThis !== 'undefined' ? globalThis : this);\n", encoding="utf-8")
    with (ROOT / "data/workbook-profiles-0.1.csv").open("w", newline="", encoding="utf-8") as out:
        writer = csv.writer(out, lineterminator="\n")
        writer.writerow(["Excel row", "Dimension", "Wx cm3", "Wx mm3", "mass kg/m", "surface m2/m", "A raw (see warnings)", "Ix cm4", "Zx cm3", "ix cm", "Iy cm4", "Wy cm3", "Zy cm3", "iy cm", "Kv cm4", "Wv cm3", "Review notes"])
        for p in data["profiles"]:
            writer.writerow([p["row"], *p["columns"].values(), " | ".join(p["validityWarnings"])])
    with (ROOT / "data/workbook-buckling-0.1.csv").open("w", newline="", encoding="utf-8") as out:
        writer = csv.writer(out, lineterminator="\n")
        writer.writerow(["Excel row", "Slenderness", "Allowable stress MPa"])
        writer.writerows((r["row"], r["lambda"], r["stress"]) for r in data["buckling"])
    print(f"Exported {len(data['sheets'])} models, {len(data['profiles'])} profiles, {len(data['buckling'])} buckling rows.")


if __name__ == "__main__":
    main()
